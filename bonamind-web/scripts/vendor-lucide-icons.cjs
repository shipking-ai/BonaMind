#!/usr/bin/env node
/**
 * vendor-lucide-icons.cjs
 *
 * One-time (re-runnable) codegen that turns BonaMind's runtime dependency on
 * `lucide-react` into source we own. It scans src/ for every icon name the app
 * imports from lucide-react, reads that icon's ISC-licensed SVG shape data from
 * node_modules, and emits `src/components/icons/icons.generated.ts` — plain
 * components built on our own factory (createIcon). After this runs, the
 * `lucide-react` import specifier is rewired to `@/components/icons` and the
 * package can be removed.
 *
 * Usage:  node scripts/vendor-lucide-icons.cjs
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const ESM = path.join(ROOT, 'node_modules', 'lucide-react', 'dist', 'esm');
const BARREL = path.join(ESM, 'lucide-react.js');
const OUT = path.join(SRC, 'components', 'icons', 'icons.generated.ts');

function* walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(p);
    else if (/\.(ts|tsx)$/.test(entry.name)) yield p;
  }
}

// 0. Build a name -> icon-file map from lucide's own barrel. This resolves
//    every alias/deprecated name (Loader2 -> loader-circle, Home -> house, ...)
//    exactly the way the library does, so we never guess a filename.
const nameToFile = new Map();
{
  const barrel = fs.readFileSync(BARREL, 'utf8');
  const exportRe = /export \{([^}]+)\} from '\.\/icons\/([^']+)';/g;
  for (const m of barrel.matchAll(exportRe)) {
    const file = m[2];
    for (const nm of m[1].matchAll(/default as ([A-Za-z0-9_$]+)/g)) {
      nameToFile.set(nm[1], file);
    }
  }
}

// 1. Collect every named import/re-export from lucide-react across src.
const names = new Set();
const importRe = /(?:import|export)\s*(?:type\s*)?\{([^}]+)\}\s*from\s*['"]lucide-react['"]/g;
for (const file of walk(SRC)) {
  const text = fs.readFileSync(file, 'utf8');
  for (const m of text.matchAll(importRe)) {
    // Strip // comments (CustomIcons' block is annotated) before splitting.
    const block = m[1].replace(/\/\/[^\n]*/g, '');
    for (const item of block.split(',')) {
      const clean = item.trim().split(/\s+as\s+/)[0].trim();
      if (clean && clean !== 'LucideIcon') names.add(clean);
    }
  }
}

const RESERVED_EXPORT_NAMES = new Set(['Infinity', 'NaN', 'undefined']);

// 2. Read each icon's shape data via the barrel map.
const sorted = [...names].sort();
const missing = [];
const defs = [];
for (const name of sorted) {
  const rel = nameToFile.get(name);
  if (!rel) {
    missing.push(`${name} (not exported by lucide barrel)`);
    continue;
  }
  const file = path.join(ESM, 'icons', path.basename(rel));
  if (!fs.existsSync(file)) {
    missing.push(`${name} -> ${rel} (file missing)`);
    continue;
  }
  const text = fs.readFileSync(file, 'utf8');
  const m = text.match(/const __iconNode = (\[[\s\S]*?\]);/);
  if (!m) {
    missing.push(`${name} (no __iconNode in ${path.basename(rel)})`);
    continue;
  }
  defs.push({ name, node: m[1] });
}

if (missing.length) {
  console.error('MISSING ICONS:');
  missing.forEach((x) => console.error('  ' + x));
  process.exit(1);
}

// 3. Emit the generated module.
const header = `// AUTO-GENERATED by scripts/vendor-lucide-icons.cjs — DO NOT EDIT BY HAND.
//
// Icon shapes vendored from the ISC-licensed lucide set (lucide-react v0.562.0),
// rendered through BonaMind's own factory in ./createIcon. Regenerate with:
//   node scripts/vendor-lucide-icons.cjs
import { createIcon, type IconNode } from './createIcon';
`;

const body = defs
  .map(({ name, node }) => {
    const exportName = RESERVED_EXPORT_NAMES.has(name) ? `${name}Icon` : name;
    return `export const ${exportName} = createIcon('${name}', ${node} as IconNode);`;
  })
  .join('\n\n');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, header + '\n' + body + '\n', 'utf8');

console.log(`Generated ${defs.length} icons -> ${path.relative(ROOT, OUT)}`);
